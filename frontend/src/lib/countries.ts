export function countryName(code: string | null | undefined): string {
  const c = (code || "").trim().toUpperCase();
  return COUNTRIES.find((x) => x.code === c)?.name || c;
}

export function countriesForPicker(query = ""): Country[] {
  const needle = query.trim().toLowerCase();
  const pin = new Map<string, number>(
    COUNTRY_PIN_ORDER.map((c, i) => [c, i])
  );
  let list = [...COUNTRIES];
  if (needle) {
    const q = query.trim();
    list = list.filter(
      (c) =>
        c.name.includes(q) ||
        c.code.toLowerCase().includes(needle) ||
        c.name.toLowerCase().includes(needle)
    );
  }
  return list.sort((a, b) => {
    const pa = pin.get(a.code) ?? 1000;
    const pb = pin.get(b.code) ?? 1000;
    if (pa !== pb) return pa - pb;
    return a.name.localeCompare(b.name, "fa");
  });
}
